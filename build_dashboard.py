SERIES_KEYS = ["t", "gini", "between_share", "theil_between", "theil_within",
               "coop_rate", "coop_in", "coop_out", "ingroup_bias", "destitute_frac",
               "assortativity", "mean_wealth", "rank_persistence_recent",
               "top1_share", "top10_share", "bottom10_share"]


def r4(xs):
    return [None if x is None else round(float(x), 4) for x in xs]


def main():
    scen = json.loads((OUT / "scenarios.json").read_text())
    sweeps = json.loads((OUT / "sweeps.json").read_text())

    payload_scen = {}
    for key, d in scen.items():
        s = d["series"]
        series = {k: (s["t"] if k == "t" else r4(s[k])) for k in SERIES_KEYS if k in s}
        for g in range(3):
            for pre in GROUP_SERIES_KEYS:
                series[f"{pre}{g}"] = r4(s[f"{pre}{g}"])
        payload_scen[key] = {
            "title": TITLES.get(key, key),
            "note": NOTES.get(key, ""),
            "series": series,
            "final": {k: round(float(v), 5) for k, v in d["final"].items()},
            "coop_matrix": [[round(float(v), 4) for v in row] for row in d["coop_matrix"]],
        }

    payload_sweeps = {}
    for key, sw in sweeps.items():
        meta = SWEEP_META[key]
        payload_sweeps[key] = {
            "title": meta["title"], "desc": meta["desc"],
            "x_label": meta["x_label"], "y_label": meta["y_label"],
            "x": sw["x"], "y": sw["y"],
            "cells": [{k: (round(float(v), 5) if isinstance(v, (int, float)) else v)
                       for k, v in c.items() if k in ("x", "y") or k in METRICS}
                      for c in sw["cells"]],
        }

    payload = {
        "meta": {
            "group_names": GROUP_NAMES,
            "pop_shares": POP_SHARES,
            "metrics": METRICS,
            "compare_metrics": COMPARE,
        },
        "scenarios": payload_scen,
        "sweeps": payload_sweeps,
    }

    tpl = (ROOT / "viewer" / "template.html").read_text()
    blob = json.dumps(payload, separators=(",", ":"))
    # the payload rides inside a <script type="application/json"> block
    blob = blob.replace("</", "<\\/")
    html = tpl.replace("__PAYLOAD__", blob)
    dest = OUT / "resource_distribution_dashboard.html"
    dest.write_text(html)
    print(f"wrote {dest}  ({len(html)/1024:.0f} KB)")


if __name__ == "__main__":
    main()
